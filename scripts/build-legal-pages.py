def patch_site_html(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    original = text
    rel = path.parent.relative_to(ROOT)
    depth = len(rel.parts)

    if depth == 0:
        ua = "documents/#user-agreement"
        docs = "documents/"
    elif rel == Path("documents"):
        ua = "#user-agreement"
        docs = "./"
    elif str(rel).startswith("documents"):
        ua = "../#user-agreement"
        docs = "../"
    else:
        prefix = "../" * depth
        ua = f"{prefix}documents/#user-agreement"
        docs = f"{prefix}documents/"

    text = text.replace('href="documents/user-agreement/"', 'href="documents/#user-agreement"')
    text = re.sub(
        r'href="(\.\./)*documents/user-agreement/"',
        lambda m: f'href="{m.group(1) or ""}documents/#user-agreement"',
        text,
    )
    text = text.replace(
        '<li class="footer__col-item--desktop-only"><span class="footer__col-inactive">Пользовательское соглашение</span></li>',
        f'<li class="footer__col-item--desktop-only"><a href="{ua}">Пользовательское соглашение</a></li>',
    )
    text = re.sub(
        r'<span class="footer__col-inactive">Пользовательское соглашение</span>',
        f'<a href="{ua}">Пользовательское соглашение</a>',
        text,
        count=1,
    )
    text = re.sub(
        r'\s*<button class="maps-dropdown__item"[^>]*maps\.google\.com[^>]*>.*?</button>',
        "",
        text,
        flags=re.S,
    )

    if text != original:
        path.write_text(text, encoding="utf-8")
        print(f"patched {path.relative_to(ROOT)}")


def main() -> int:
    if not TEMPLATE.exists():
        print("Template not found:", TEMPLATE, file=sys.stderr)
        return 1

    template = TEMPLATE.read_text(encoding="utf-8")

    # hub
    hub = build_hub(template)
    (OUT_DIR / "index.html").write_text(hub, encoding="utf-8")
    print("wrote documents/index.html")

    # subpages — redirect to hub with hash
    for page in PAGES:
        out = OUT_DIR / page["slug"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(build_redirect_page(page), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")

    # patch all other html
    for path in ROOT.rglob("*.html"):
        if path.parts[-2:] == ("documents", "index.html"):
            continue
        if path.parent.parent.name == "documents" and path.name == "index.html":
            continue
        patch_site_html(path)

    return 0


