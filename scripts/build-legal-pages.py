def docs_hash_href(depth: int, slug: str) -> str:
    if depth == 0:
        return f"documents/#{slug}" if slug else "documents/"
    if depth == 1:
        return f"#{slug}" if slug else "./"
    prefix = asset_prefix(depth)
    return f"{prefix}documents/#{slug}" if slug else f"{prefix}documents/"


def asset_prefix(depth: int) -> str:
    return "../" * depth


def docs_href(depth: int, slug: str) -> str:
    if depth == 0:
        return f"documents/{slug}/"
    if depth == 1 and slug:
        return f"{slug}/"
    prefix = asset_prefix(depth)
    return f"{prefix}documents/{slug}/" if slug else f"{prefix}documents/"


def patch_paths(html: str, depth: int) -> str:
    prefix = asset_prefix(depth)
    html = html.replace('href="../', f'href="{prefix}')
    html = html.replace('src="../', f'src="{prefix}')
    html = html.replace('url(\'../', f"url('{prefix}")
    html = html.replace('url("../', f'url("{prefix}')
    return html


def replace_main(html: str, main_html: str) -> str:
    return re.sub(r"<main>.*?</main>", main_html, html, count=1, flags=re.S)


